/**
 * Number of weeks of execution history to sync for dashboard metrics.
 * Running executions bypass this window on the first initial-sync request.
 */
const EXECUTION_SYNC_WEEKS = 5

// Derive TypeScript type from Effect Schema (encoded form for JSON storage)
export type ExecutionDocType = ES.Schema.Encoded<typeof ExecutionSchema>

// Use pre-generated RxDB-compatible JSON Schema (generated by cli/generate-rxdb)
export const executionSchema: RxJsonSchema<ExecutionDocType> = {
  title: "Executions",
  version: 14,
  primaryKey: "id",
  type: "object",
  additionalProperties: false,
  properties:
    executionRxdbSchema.properties as RxJsonSchema<ExecutionDocType>["properties"],
  indexes: [],
  required: executionRxdbSchema.required as StringKeys<ExecutionDocType>[],
}

