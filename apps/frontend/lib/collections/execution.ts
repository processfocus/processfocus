export const pullQueryBuilder = (
  checkpoint: PullCheckpoint | undefined,
  limit: number,
) => {
  // Initial sync includes all Running executions plus recent terminal history.
  // Subsequent syncs use the stored checkpoint for incremental updates.
  const historySince =
    Date.now() - EXECUTION_SYNC_WEEKS * 7 * 24 * 60 * 60 * 1000
  const effectiveCheckpoint: PullCheckpoint = checkpoint ?? {
    id: "",
    updatedAt: historySince,
  }

  const query = gql /* GraphQL */`
    query PullExecution($checkpoint: PullCheckpoint, $limit: Int!, $includeRunning: Boolean, $historySince: Float) {
      pullExecution(checkpoint: $checkpoint, limit: $limit, includeRunning: $includeRunning, historySince: $historySince) {
        documents {
          id
          updatedAt
          processStateId
          withoutWaiting
          processName
          processPath
          canAbandonExecution
          canRestartExecution
          status
          failureReason
          abandonedReason
          notStartedReason
          startedAt
          finishedAt
          completedSteps
          totalSteps
          durationMs
          estimatedCompletionAt
          slaWarningAt
          slaTargetAt
          deleted
          steps {
            id
            name
            path
            status
            failureReason
            notStartedReason
            role {
              id
              name
            }
            submittedViaEmbeddedForm
            externalSubmitterEmail
            assignedProviderUserEmail
            providerUser {
              id
              firstName
              lastName
              picture
              orgUnit
            }
            startedAt
            completedAt
          }
        }
        checkpoint {
          id
          updatedAt
        }
      }
    }
  `
  return {
    query,
    operationName: "PullExecution",
    variables: {
      checkpoint: effectiveCheckpoint,
      includeRunning: checkpoint === undefined,
      historySince,
      limit,
    } satisfies PullExecutionQueryVariables,
  }
}

